import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sequelize from '../lib/database.js';
import { select, execute, text, userDepotIds } from './sales.js';
import { buildSalesSummaryReport } from '../lib/salesSummaryReport.js';

// End of Month Sales (old PHP Freezed). Freezing a month locks that month's sales, sales returns and credit / debit
// notes (freezed = 1) and records it in freezed_month_details, which the Sales, Sample / Expiry and Sales Return
// screens check before saving or deleting. A freezed month's sales summary Excel is generated from here too.
// Admin only (old PHP: role_id 1).

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const ADMIN_ROLE = 1;
// Old PHP offered the current year and the 5 before it
const YEARS_BACK = 5;

// Sales summary reports generated by the old PHP app live on its server
const PHP_REPORT_URL = 'https://erp.eatanytime.in/eat_erp/assets/reports/sales_summary/';
// Reports generated here are kept outside the public assets folder and downloaded through the API (admin only):
// they hold the whole month's sales and their names are just timestamps.
const REPORT_DIR = 'reports/sales_summary/';
const REPORT_PATH = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', REPORT_DIR);

const isAdmin = (req) => +req.userData.userRoleId === ADMIN_ROLE;
const noAccess = (res) => res.status(401).json({ message: "You do not have access to this page." });
const pad = (value) => String(value).padStart(2, '0');

const offeredYears = () => {
  const currentYear = new Date().getFullYear();
  return Array.from({ length: YEARS_BACK + 1 }, (_, index) => currentYear - index);
};

// Months of a year up to the previous month (old PHP get_freez_month stopped at the current month)
const listedMonths = (year) => {
  const now = new Date();
  if (year > now.getFullYear()) return [];
  const last = year === now.getFullYear() ? now.getMonth() : 12;
  return MONTHS.slice(0, last);
};

// { year, month, monthNo, fromDate, toDate, nextDate } of a listed month, or null
const parseMonth = (source) => {
  const year = +(source || {}).year || 0;
  const month = text((source || {}).month);
  const monthNo = MONTHS.indexOf(month) + 1;
  if (!offeredYears().includes(year) || !listedMonths(year).includes(month)) return null;
  const next = new Date(year, monthNo, 1);
  return {
    year,
    month,
    monthNo,
    fromDate: `${year}-${pad(monthNo)}-01`,
    toDate: `${year}-${pad(monthNo)}-${pad(new Date(year, monthNo, 0).getDate())}`,
    nextDate: `${next.getFullYear()}-${pad(next.getMonth() + 1)}-01`
  };
};

const findFreezed = async (year, month, transaction, lock = false) => {
  const rows = await select(
    `select id, report_path, report_name from freezed_month_details where year = :year and month = :month order by id limit 1${lock ? ' for update' : ''}`,
    { year, month }, transaction
  );
  return rows[0] || null;
};

// A report generated by this backend (as opposed to one on the old PHP server)
const isLocalReport = (row) => !!row && text(row.report_path) === REPORT_DIR && !!text(row.report_name);
// Only a plain file name, so a stored name can never point outside the report folder
const localReportFile = (row) => path.join(REPORT_PATH, path.basename(text(row.report_name)));

export const getMonths = async (req, res, next) => {
  try {
    if (!isAdmin(req)) return noAccess(res);
    const years = offeredYears();
    const year = years.includes(+req.query.year) ? +req.query.year : years[0];
    const freezed = await select(
      `select F.id, F.month, F.added_on, F.report_path, F.report_name, concat(ifnull(U.first_name, ''), ' ', ifnull(U.last_name, '')) as added_by_name
       from freezed_month_details F left join user_master U on (F.added_by = U.id)
       where F.year = :year order by F.id`,
      { year }
    );
    const months = listedMonths(year).map((month, index) => {
      const row = freezed.find((item) => text(item.month) === month);
      const hasReport = !!row && !!text(row.report_name);
      return {
        month_no: index + 1,
        month,
        freezed: !!row,
        added_on: row ? row.added_on : null,
        added_by: row ? text(row.added_by_name) : '',
        report_name: hasReport ? row.report_name : null,
        // Local reports are downloaded through GET /report; old PHP ones are still on the PHP server
        report_local: hasReport && isLocalReport(row),
        report_url: hasReport && !isLocalReport(row) ? PHP_REPORT_URL + encodeURIComponent(row.report_name) : null
      };
    });
    res.status(200).json({ year, years, months });
  } catch (error) {
    res.statusCode = 500;
    res.message = "Fetching freezed months failed!";
    next(error, req, res);
  }
};

// Old PHP Freezed_model::save_freeze_detail
export const freezeMonth = async (req, res, next) => {
  try {
    if (!isAdmin(req)) return noAccess(res);
    const period = parseMonth(req.body);
    // PHP only hid the button; also refuse months that are not over yet
    if (!period) {
      return res.status(422).json({ message: "Only past months of the listed years can be freezed." });
    }
    const { year, month, fromDate, nextDate } = period;

    const t = await sequelize.transaction();
    try {
      if (await findFreezed(year, month, t, true)) {
        await t.rollback();
        return res.status(422).json({ message: `${month} ${year} is already freezed.` });
      }
      await execute(
        `insert into freezed_month_details (year, month, added_on, added_by) values (:year, :month, :now, :userId)`,
        { year, month, now: new Date(), userId: req.userData.userId }, t
      );
      // Date ranges (not month() / year()) so the date indexes are used
      const replacements = { fromDate, nextDate };
      const inMonth = (column) => `(${column} >= :fromDate and ${column} < :nextDate)`;
      const lock = async (table, condition) => {
        // Rows of the month, and how many of them were not locked yet (many old rows were already locked by PHP)
        const [count] = await select(
          `select count(*) as total, sum(case when freezed = 1 then 0 else 1 end) as unlocked from ${table} where ${condition}`,
          replacements, t
        );
        const total = +count.total || 0;
        if (!+count.unlocked) return { total, locked: 0 };
        const [result] = await execute(
          `update ${table} set freezed = 1 where (freezed is null or freezed <> 1) and ${condition}`,
          replacements, t
        );
        return { total, locked: result && typeof result.affectedRows === 'number' ? result.affectedRows : 0 };
      };
      // Sales: by invoice date once invoiced, else by date of processing
      const sales = await lock('distributor_out',
        `((ifnull(invoice_no, '') = '' and ${inMonth('date_of_processing')}) or (ifnull(invoice_no, '') <> '' and ${inMonth('invoice_date')}))`);
      // Sales returns: by approval date once approved, else by date of processing
      const salesReturns = await lock('distributor_in',
        `((approved_on is not null and ${inMonth('approved_on')}) or (approved_on is null and ${inMonth('date_of_processing')}))`);
      // Credit / debit notes: by approval date once approved, else by transaction date
      const creditDebitNotes = await lock('credit_debit_note',
        `((approved_on is not null and ${inMonth('approved_on')}) or (approved_on is null and ${inMonth('date_of_transaction')}))`);
      await t.commit();
      res.status(200).json({ message: `${month} ${year} freezed.`, sales, salesReturns, creditDebitNotes });
    } catch (error) {
      if (!t.finished) await t.rollback();
      throw error;
    }
  } catch (error) {
    res.statusCode = 500;
    res.message = "Freezing month failed!";
    next(error, req, res);
  }
};

// Old PHP Export::generate_sales_summary_report: the sales summary Excel of a freezed month, saved and linked on
// freezed_month_details. Generating again replaces the report (and removes the previous file made here).
export const generateReport = async (req, res, next) => {
  try {
    if (!isAdmin(req)) return noAccess(res);
    const period = parseMonth(req.body);
    if (!period) {
      return res.status(422).json({ message: "Select a past month of the listed years." });
    }
    const { year, month, fromDate, toDate } = period;
    // PHP only showed Generate for freezed months
    const freezed = await findFreezed(year, month);
    if (!freezed) {
      return res.status(422).json({ message: `Freeze ${month} ${year} before generating its report.` });
    }
    const depotIds = userDepotIds(req);
    if (!depotIds.length) {
      return res.status(422).json({ message: "No depots are assigned to your user." });
    }

    const report = await buildSalesSummaryReport({ fromDate, toDate, depotIds });

    // PHP date('d-m-Y_H-i-A')
    const now = new Date();
    const stamp = `${pad(now.getDate())}-${pad(now.getMonth() + 1)}-${now.getFullYear()}_${pad(now.getHours())}-${pad(now.getMinutes())}-${now.getHours() < 12 ? 'AM' : 'PM'}`;
    const reportName = `Sale_Summary_Report_${stamp}.xlsm`;
    await fs.promises.mkdir(REPORT_PATH, { recursive: true });
    await fs.promises.writeFile(path.join(REPORT_PATH, reportName), report.buffer);
    await execute(
      `update freezed_month_details set report_path = :reportPath, report_name = :reportName where year = :year and month = :month`,
      { reportPath: REPORT_DIR, reportName, year, month }
    );
    // The previous report of this backend is no longer linked anywhere
    if (isLocalReport(freezed) && path.basename(text(freezed.report_name)) !== reportName) {
      await fs.promises.unlink(localReportFile(freezed)).catch(() => {});
    }
    res.status(200).json({
      message: `Sales summary report of ${month} ${year} generated (${report.summaryRows} summary and ${report.detailRows} detailed rows).`,
      report_name: reportName,
      summaryRows: report.summaryRows,
      detailRows: report.detailRows
    });
  } catch (error) {
    res.statusCode = 500;
    res.message = "Generating sales summary report failed!";
    next(error, req, res);
  }
};

// Downloads the report generated here for a month (GET ?year=&month=)
export const downloadReport = async (req, res, next) => {
  try {
    if (!isAdmin(req)) return noAccess(res);
    const period = parseMonth(req.query);
    const freezed = period ? await findFreezed(period.year, period.month) : null;
    if (!isLocalReport(freezed)) {
      return res.status(404).json({ message: "No report has been generated for this month yet." });
    }
    const file = localReportFile(freezed);
    try {
      await fs.promises.access(file);
    } catch (error) {
      return res.status(404).json({ message: "The report file is missing. Generate it again." });
    }
    res.download(file, path.basename(file));
  } catch (error) {
    res.statusCode = 500;
    res.message = "Downloading sales summary report failed!";
    next(error, req, res);
  }
};
